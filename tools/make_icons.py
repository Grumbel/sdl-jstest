"""Generates every icon from data/icons/<prog>.svg (gamepkgstd INT-4).

Writes, for each program:
  data/icons/<size>/<prog>.png       hicolor sizes (INT-6), Android and
                                     PortMaster take theirs from here
  src/icons/<prog>_icon.h            32x32 ARGB pixels for SDL_SetWindowIcon
                                     (INT-9), so no image loader is needed
  data/icons/<prog>.ico              16..256, embedded in the Windows .exe
                                     (INT-10)

The output is committed; run this again after changing an SVG:

  nix shell nixpkgs#librsvg nixpkgs#python3Packages.pillow -c python3 tools/make_icons.py
"""

import os
import subprocess
import sys

from PIL import Image

PROGRAMS = ["sdl1-jstest", "sdl2-jstest", "sdl3-jstest"]
SIZES = [16, 24, 32, 48, 64, 72, 96, 128, 144, 192, 256]
ICO_SIZES = [16, 24, 32, 48, 64, 256]
WINDOW_ICON_SIZE = 32


def render(svg: str, size: int, png: str) -> None:
    os.makedirs(os.path.dirname(png), exist_ok=True)
    subprocess.run(["rsvg-convert", "--width", str(size), "--height", str(size),
                    "--keep-aspect-ratio", "--output", png, svg], check=True)


def write_header(prog: str, png: str, header: str) -> None:
    img = Image.open(png).convert("RGBA")
    name = prog.replace("-", "_") + "_icon"
    px = img.load()
    words = []
    for y in range(img.height):
        for x in range(img.width):
            r, g, b, a = px[x, y]
            words.append("0x%02x%02x%02x%02xu" % (a, r, g, b))
    lines = [", ".join(words[i:i + 6]) for i in range(0, len(words), 6)]
    os.makedirs(os.path.dirname(header), exist_ok=True)
    with open(header, "w") as fp:
        # REUSE-IgnoreStart
        fp.write("// SPDX-FileCopyrightText: 2026 Ingo Ruhnke <grumbel@gmail.com>\n"
                 "// SPDX-License-Identifier: GPL-3.0-or-later\n\n"
                 "/* Generated by tools/make_icons.py from data/icons/%s.svg. */\n\n"
                 "#pragma once\n\n"
                 "#include <stdint.h>\n\n"
                 "#define %s_SIZE %d\n\n"
                 "/* ARGB8888, row by row. */\n"
                 "static const uint32_t %s[%d * %d] = {\n    %s\n};\n"
                 % (prog, name.upper(), img.width, name, img.width, img.height,
                    ",\n    ".join(lines)))
        # REUSE-IgnoreEnd


def write_ico(prog: str, icon_dir: str) -> None:
    # Each size from its own rendering, not scaled down from 256; Pillow
    # stores the 256 px entry PNG-compressed.
    images = [Image.open(os.path.join(icon_dir, str(size), prog + ".png")).convert("RGBA")
              for size in ICO_SIZES]
    images[-1].save(os.path.join(icon_dir, prog + ".ico"), format="ICO",
                    sizes=[(s, s) for s in ICO_SIZES], append_images=images[:-1])


def main() -> int:
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    for prog in PROGRAMS:
        svg = os.path.join(root, "data", "icons", prog + ".svg")
        for size in SIZES:
            render(svg, size, os.path.join(root, "data", "icons", str(size), prog + ".png"))
        write_ico(prog, os.path.join(root, "data", "icons"))
        write_header(prog, os.path.join(root, "data", "icons", str(WINDOW_ICON_SIZE), prog + ".png"),
                     os.path.join(root, "src", "icons", prog.replace("-", "_") + "_icon.h"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
